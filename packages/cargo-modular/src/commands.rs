use crate::stubs::{self, Names};
use anyhow::{anyhow, bail, Context, Result};
use heck::{ToKebabCase, ToPascalCase, ToSnakeCase};
use std::fs;
use std::path::{Path, PathBuf};
use toml_edit::{value, DocumentMut, InlineTable, Item, Table};

const RESERVED: &[&str] = &[
    "src", "core", "std", "alloc", "test", "target", "modules", "packages", "xtask",
];
const REGISTRY_DIR: &str = "packages/modules-registry";
const REGISTRY_HEADER: &str = "// @generated by `cargo modular`. Run `cargo modular modules:sync` to rebuild; do not edit by hand.\n";

pub fn resolve_root(root: Option<PathBuf>) -> Result<PathBuf> {
    if let Some(root) = root {
        return Ok(root);
    }
    let mut dir = std::env::current_dir()?;
    loop {
        let manifest = dir.join("Cargo.toml");
        if manifest.is_file() && fs::read_to_string(&manifest)?.contains("[workspace]") {
            return Ok(dir);
        }
        if !dir.pop() {
            bail!("no Cargo workspace found; run inside the project or pass --root");
        }
    }
}

pub fn normalize_name(raw: &str) -> Result<Names> {
    let kebab = raw.trim().to_kebab_case();
    let allowed_input = raw
        .trim()
        .chars()
        .all(|c| c.is_ascii_alphanumeric() || matches!(c, '-' | '_' | ' '));
    let valid = allowed_input
        && !kebab.is_empty()
        && kebab.chars().next().is_some_and(|c| c.is_ascii_lowercase())
        && kebab
            .chars()
            .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-');
    if !valid {
        bail!("`{raw}` is not a valid module name; use letters, digits and dashes, starting with a letter");
    }
    if RESERVED.contains(&kebab.as_str()) {
        bail!("`{kebab}` is a reserved name");
    }
    Ok(Names {
        snake: kebab.to_snake_case(),
        pascal: kebab.to_pascal_case(),
        kebab,
    })
}

pub fn make_module(root: &Path, raw: &str, dry_run: bool) -> Result<()> {
    let names = normalize_name(raw)?;
    let module_dir = root.join("modules").join(&names.kebab);
    if module_dir.exists() {
        bail!(
            "module `{}` already exists at {}",
            names.kebab,
            module_dir.display()
        );
    }

    let files: Vec<(&str, &str)> = vec![
        ("Cargo.toml", stubs::CARGO_TOML),
        ("README.md", stubs::README),
        ("src/lib.rs", stubs::LIB_RS),
        ("src/controllers/mod.rs", stubs::CONTROLLERS_RS),
        ("src/migrations/mod.rs", stubs::MIGRATIONS_RS),
        ("src/commands/mod.rs", stubs::COMMANDS_MOD),
        ("templates/.gitkeep", ""),
        ("tests/.gitkeep", ""),
    ];

    for (path, _) in &files {
        println!(
            "{} modules/{}/{}",
            if dry_run { "would create" } else { "create" },
            names.kebab,
            path
        );
    }
    println!(
        "{} Cargo.toml (workspace member modules/*)",
        if dry_run { "would update" } else { "update" }
    );
    println!(
        "{} packages/modules-registry (dependency + module list)",
        if dry_run { "would update" } else { "update" }
    );
    if dry_run {
        return Ok(());
    }

    for (path, template) in files {
        let target = module_dir.join(path);
        fs::create_dir_all(target.parent().expect("file has a parent"))?;
        fs::write(&target, stubs::render(template, &names))?;
    }
    register_dependency(root, &names)?;
    modules_sync(root)?;
    println!("\nmodule `{}` ready; build with `cargo build`", names.kebab);
    Ok(())
}

fn register_dependency(root: &Path, names: &Names) -> Result<()> {
    // The workspace must include modules/* so cargo builds the new crate.
    let root_manifest = root.join("Cargo.toml");
    let mut root_doc: DocumentMut = fs::read_to_string(&root_manifest)?
        .parse()
        .context("invalid root Cargo.toml")?;
    let workspace = root_doc
        .get_mut("workspace")
        .and_then(Item::as_table_mut)
        .ok_or_else(|| anyhow!("root Cargo.toml has no [workspace]"))?;
    let members = workspace
        .entry("members")
        .or_insert(value(toml_edit::Array::new()));
    let members = members
        .as_array_mut()
        .ok_or_else(|| anyhow!("workspace.members is not an array"))?;
    if !members
        .iter()
        .any(|member| member.as_str() == Some("modules/*"))
    {
        members.push("modules/*");
    }
    fs::write(&root_manifest, root_doc.to_string())?;

    // The registry crate depends on every module; the app and migrator depend on the registry.
    let registry_manifest = root.join(REGISTRY_DIR).join("Cargo.toml");
    if !registry_manifest.is_file() {
        bail!(
            "{} not found; the project needs a modules-registry crate",
            registry_manifest.display()
        );
    }
    let mut doc: DocumentMut = fs::read_to_string(&registry_manifest)?
        .parse()
        .context("invalid registry Cargo.toml")?;
    let dependencies = doc
        .entry("dependencies")
        .or_insert(Item::Table(Table::new()));
    let dependencies = dependencies
        .as_table_mut()
        .ok_or_else(|| anyhow!("[dependencies] is not a table"))?;
    let mut spec = InlineTable::new();
    spec.insert("path", format!("../../modules/{}", names.kebab).into());
    dependencies.insert(&format!("module-{}", names.kebab), value(spec));
    fs::write(&registry_manifest, doc.to_string())?;
    Ok(())
}

/// Runs the project binary (`cargo run --quiet -- <args>`) in the project root with inherited output.
pub fn run_project(root: &Path, args: &[&str]) -> Result<()> {
    let status = std::process::Command::new("cargo")
        .args(["run", "--quiet", "--"])
        .args(args)
        .current_dir(root)
        .status()
        .context("failed to start cargo")?;
    if !status.success() {
        bail!("`cargo run -- {}` exited with {status}", args.join(" "));
    }
    Ok(())
}

pub fn command_list(root: &Path) -> Result<()> {
    run_project(root, &["task"])
}

pub fn command_run(root: &Path, signature: &str, args: &[String]) -> Result<()> {
    let mut all = vec!["task", signature];
    all.extend(args.iter().map(String::as_str));
    run_project(root, &all)
}

pub fn schedule_list(root: &Path) -> Result<()> {
    run_project(root, &["scheduler", "--list"])
}

pub fn schedule_work(root: &Path) -> Result<()> {
    run_project(root, &["scheduler"])
}

/// Creates a command (a Loco task). Inside a module it is registered in `src/commands/mod.rs`;
/// without a module the request is passed to Loco's own `generate task`.
pub fn make_command(
    root: &Path,
    raw: &str,
    module: Option<&str>,
    signature: Option<&str>,
    dry_run: bool,
) -> Result<()> {
    let names = normalize_name(raw)?;
    let Some(module) = module else {
        println!("no --module given: using Loco's generator for an app-level task");
        if dry_run {
            println!("would run: cargo run -- generate task {}", names.snake);
            return Ok(());
        }
        return run_project(root, &["generate", "task", &names.snake]);
    };

    let module = normalize_name(module)?;
    let module_dir = root.join("modules").join(&module.kebab);
    if !module_dir.join("Cargo.toml").is_file() {
        bail!(
            "module `{}` does not exist; create it with `cargo modular make:module {}`",
            module.kebab,
            module.kebab
        );
    }
    let signature = signature
        .map(str::to_string)
        .unwrap_or_else(|| format!("{}:{}", module.kebab, names.kebab));
    if !signature
        .chars()
        .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || matches!(c, ':' | '-' | '_'))
    {
        bail!("signature `{signature}` may only use lowercase letters, digits, `:`, `-` and `_`");
    }

    let file = module_dir
        .join("src")
        .join("commands")
        .join(format!("{}.rs", names.snake));
    let registry_file = module_dir.join("src").join("commands").join("mod.rs");
    if file.exists() {
        bail!("command file {} already exists", file.display());
    }
    let registry = fs::read_to_string(&registry_file).with_context(|| {
        format!(
            "{} not found; this module predates commands",
            registry_file.display()
        )
    })?;
    const MODS: &str = "// mods-inject (do not remove)";
    const TASKS: &str = "// tasks-inject (do not remove)";
    if !registry.contains(MODS) || !registry.contains(TASKS) {
        bail!(
            "{} is missing its `mods-inject` / `tasks-inject` markers",
            registry_file.display()
        );
    }
    if registry.contains(&format!("mod {};", names.snake)) {
        bail!("a command named `{}` is already registered", names.snake);
    }

    println!(
        "{} {}",
        if dry_run { "would create" } else { "create" },
        file.display()
    );
    println!(
        "{} {} (register `{signature}`)",
        if dry_run { "would update" } else { "update" },
        registry_file.display()
    );
    if dry_run {
        return Ok(());
    }

    let body = stubs::COMMAND
        .replace("{{task_pascal}}", &names.pascal)
        .replace("{{signature}}", &signature);
    fs::write(&file, body)?;
    let updated = registry
        .replace(MODS, &format!("mod {};\n{MODS}", names.snake))
        .replace(
            TASKS,
            &format!(
                "tasks.register({}::{});\n    {TASKS}",
                names.snake, names.pascal
            ),
        );
    fs::write(&registry_file, updated)?;
    println!("\nrun it with: cargo modular command:run {signature}");
    Ok(())
}

/// Module directories that contain a Cargo.toml, sorted.
pub fn discover(root: &Path) -> Result<Vec<String>> {
    let dir = root.join("modules");
    if !dir.is_dir() {
        return Ok(Vec::new());
    }
    let mut found = Vec::new();
    for entry in fs::read_dir(dir)? {
        let entry = entry?;
        if entry.path().join("Cargo.toml").is_file() {
            found.push(entry.file_name().to_string_lossy().into_owned());
        }
    }
    found.sort();
    Ok(found)
}

pub fn render_registry(modules: &[String]) -> String {
    let mut out = String::from(REGISTRY_HEADER);
    out.push_str("use loco_modular::Module;\n\n");
    out.push_str("pub fn all() -> Vec<Box<dyn Module>> {\n    vec![\n");
    for module in modules {
        out.push_str(&format!(
            "        Box::new(module_{}::{}Module),\n",
            module.to_snake_case(),
            module.to_pascal_case()
        ));
    }
    out.push_str("    ]\n}\n");
    out
}

pub fn modules_sync(root: &Path) -> Result<()> {
    let modules = discover(root)?;
    let path = root.join(REGISTRY_DIR).join("src").join("lib.rs");
    fs::create_dir_all(path.parent().expect("src has a parent"))?;
    fs::write(&path, render_registry(&modules))?;
    println!(
        "synced packages/modules-registry/src/lib.rs ({} module{})",
        modules.len(),
        if modules.len() == 1 { "" } else { "s" }
    );
    Ok(())
}

pub fn modules_list(root: &Path) -> Result<()> {
    let modules = discover(root)?;
    if modules.is_empty() {
        println!("no modules yet; create one with `cargo modular make:module <name>`");
    }
    let registry =
        fs::read_to_string(root.join(REGISTRY_DIR).join("src").join("lib.rs")).unwrap_or_default();
    for module in modules {
        let registered = registry.contains(&format!("module_{}::", module.to_snake_case()));
        println!(
            "{module:<28} {}",
            if registered {
                "registered"
            } else {
                "NOT registered (run modules:sync)"
            }
        );
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn project() -> tempfile::TempDir {
        let dir = tempfile::tempdir().unwrap();
        fs::write(dir.path().join("Cargo.toml"), "# keep me\n[workspace]\nmembers = [\".\"]\n\n[package]\nname = \"app\"\nversion = \"0.1.0\"\n").unwrap();
        let registry = dir.path().join("packages/modules-registry");
        fs::create_dir_all(registry.join("src")).unwrap();
        fs::write(registry.join("Cargo.toml"), "[package]\nname = \"modules-registry\"\nversion = \"0.1.0\"\n\n[dependencies]\nserde = \"1\"\n").unwrap();
        dir
    }

    #[test]
    fn names_are_normalized() {
        let names = normalize_name("Role Permission").unwrap();
        assert_eq!(
            (
                names.kebab.as_str(),
                names.snake.as_str(),
                names.pascal.as_str()
            ),
            ("role-permission", "role_permission", "RolePermission")
        );
    }

    #[test]
    fn invalid_and_reserved_names_are_rejected() {
        for bad in ["", "9lives", "src", "bad/name"] {
            assert!(normalize_name(bad).is_err(), "{bad}");
        }
    }

    #[test]
    fn make_module_creates_files_and_registers() {
        let dir = project();
        make_module(dir.path(), "blog", false).unwrap();

        assert!(dir.path().join("modules/blog/src/lib.rs").is_file());
        let lib = fs::read_to_string(dir.path().join("modules/blog/src/lib.rs")).unwrap();
        assert!(lib.contains("pub struct BlogModule;"));

        let manifest = fs::read_to_string(dir.path().join("Cargo.toml")).unwrap();
        assert!(manifest.starts_with("# keep me"));
        assert!(manifest.contains("modules/*"));

        let registry_manifest =
            fs::read_to_string(dir.path().join("packages/modules-registry/Cargo.toml")).unwrap();
        assert!(registry_manifest.contains("module-blog"));
        assert!(registry_manifest.contains("serde"));

        let registry =
            fs::read_to_string(dir.path().join("packages/modules-registry/src/lib.rs")).unwrap();
        assert!(registry.contains("Box::new(module_blog::BlogModule)"));
    }

    #[test]
    fn make_command_creates_and_registers_a_task() {
        let dir = project();
        make_module(dir.path(), "blog", false).unwrap();
        make_command(dir.path(), "Send Digest", Some("blog"), None, false).unwrap();

        let file = fs::read_to_string(dir.path().join("modules/blog/src/commands/send_digest.rs"))
            .unwrap();
        assert!(file.contains("pub struct SendDigest;"));
        assert!(file.contains("\"blog:send-digest\""));

        let registry =
            fs::read_to_string(dir.path().join("modules/blog/src/commands/mod.rs")).unwrap();
        assert!(registry.contains("mod send_digest;"));
        assert!(registry.contains("tasks.register(send_digest::SendDigest);"));
        assert!(registry.contains("// mods-inject (do not remove)"));
    }

    #[test]
    fn make_command_uses_a_custom_signature_and_rejects_duplicates() {
        let dir = project();
        make_module(dir.path(), "blog", false).unwrap();
        make_command(
            dir.path(),
            "digest",
            Some("blog"),
            Some("emails:digest"),
            false,
        )
        .unwrap();
        let file =
            fs::read_to_string(dir.path().join("modules/blog/src/commands/digest.rs")).unwrap();
        assert!(file.contains("\"emails:digest\""));
        assert!(make_command(dir.path(), "digest", Some("blog"), None, false).is_err());
        assert!(make_command(dir.path(), "x", Some("blog"), Some("Bad Sig"), false).is_err());
        assert!(make_command(dir.path(), "x", Some("missing"), None, false).is_err());
    }

    #[test]
    fn make_command_dry_run_writes_nothing() {
        let dir = project();
        make_module(dir.path(), "blog", false).unwrap();
        make_command(dir.path(), "digest", Some("blog"), None, true).unwrap();
        assert!(!dir
            .path()
            .join("modules/blog/src/commands/digest.rs")
            .exists());
    }

    #[test]
    fn existing_module_is_not_overwritten() {
        let dir = project();
        make_module(dir.path(), "blog", false).unwrap();
        assert!(make_module(dir.path(), "blog", false).is_err());
    }

    #[test]
    fn dry_run_writes_nothing() {
        let dir = project();
        make_module(dir.path(), "blog", true).unwrap();
        assert!(!dir.path().join("modules").exists());
    }

    #[test]
    fn sync_lists_modules_sorted() {
        let dir = project();
        make_module(dir.path(), "zeta", false).unwrap();
        make_module(dir.path(), "alpha-beta", false).unwrap();
        let registry =
            fs::read_to_string(dir.path().join("packages/modules-registry/src/lib.rs")).unwrap();
        assert!(registry.find("AlphaBetaModule").unwrap() < registry.find("ZetaModule").unwrap());
    }
}
