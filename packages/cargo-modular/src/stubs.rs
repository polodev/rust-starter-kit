//! File templates for a new module. `{{kebab}}`, `{{snake}}` and `{{pascal}}` are substituted.

pub struct Names {
    pub kebab: String,
    pub snake: String,
    pub pascal: String,
}

pub fn render(template: &str, names: &Names) -> String {
    template
        .replace("{{kebab}}", &names.kebab)
        .replace("{{snake}}", &names.snake)
        .replace("{{pascal}}", &names.pascal)
}

